"""
Autonomous Fix Loop — rule-based micro-bug auto-repair
======================================================

Scheduled job that runs 3× per day. Detects + fixes specific known
bug patterns in the codebase WITHOUT AI generation:

1. JSONB double-decode (json.loads on already-parsed list/dict)
2. PostgreSQL case folding ("C" quoted → c lowercase)
3. PgConnectionWrapper.cursor() legacy pattern
4. Direct %s placeholder bypassing PgCursorWrapper
5. request.json without silent=True

Each fix is APPLIED MECHANICALLY (regex + AST), not generated by AI.
This eliminates hallucination risk for production code.

After fixes:
- Runs scripts/test_full_radim_journey.py
- If 19/19 PASS → commits to `auto-fix-YYYY-MM-DD` branch + pushes
- If FAIL → reverts via git checkout, logs failure
- Sends SMS/email summary either way

SAFETY RAILS:
- Never edits files in BLOCKED_FILES whitelist (auth, payments, medical)
- Always creates feature branch (never main directly)
- Heroku deploy is MANUAL — user merges PR after review
- Daily budget cap inherited from claude_autonomous_agent
- Cooldown: same fix not applied twice in 24h (anti-loop)
"""

